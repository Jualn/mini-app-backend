-- Additive only. No legacy confirmation/submission conversion; no existing business data touched.
CREATE TABLE learning_task (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(120) NOT NULL,
 description TEXT NOT NULL,
 article_id BIGINT UNSIGNED NULL,
 requirements JSON NOT NULL,
 audience JSON NULL,
 review_required BOOLEAN NOT NULL,
 first_deadline DATETIME(6) NOT NULL,
 deadline_revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 published_at DATETIME(6) NULL,
 closed_at DATETIME(6) NULL,
 cancelled_at DATETIME(6) NULL,
 cancelled_by BIGINT UNSIGNED NULL,
 cancellation_reason VARCHAR(1000) NULL,
 CONSTRAINT fk_learning_task_article FOREIGN KEY(article_id) REFERENCES article(id),
 CONSTRAINT chk_learning_task_state CHECK(status IN ('DRAFT','PUBLISHED','CLOSED','CANCELLED')),
 CONSTRAINT chk_learning_task_publication CHECK(status='DRAFT' OR published_at IS NOT NULL),
 CONSTRAINT chk_learning_task_close CHECK(status<>'CLOSED' OR closed_at IS NOT NULL),
 CONSTRAINT chk_learning_task_cancel CHECK(status<>'CANCELLED' OR (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL AND cancellation_reason IS NOT NULL)),
 KEY idx_learning_task_admin(updated_at,id),
 KEY idx_learning_task_deadline(status,first_deadline,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE learning_task_assignment (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 task_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 allocation_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 progress VARCHAR(24) NOT NULL DEFAULT 'NOT_STARTED',
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 assigned_at DATETIME(6) NOT NULL,
 assigned_by BIGINT UNSIGNED NOT NULL,
 confirmed_at DATETIME(6) NULL,
 first_submitted_at DATETIME(6) NULL,
 on_time_first_submission BOOLEAN NULL,
 latest_submission_id BIGINT UNSIGNED NULL,
 supplement_deadline DATETIME(6) NULL,
 completed_at DATETIME(6) NULL,
 revoked_at DATETIME(6) NULL,
 revoked_by BIGINT UNSIGNED NULL,
 revocation_reason VARCHAR(1000) NULL,
 UNIQUE KEY uk_learning_task_user(task_id,user_id),
 UNIQUE KEY uk_learning_assignment_chain(id,task_id),
 CONSTRAINT fk_learning_assignment_task FOREIGN KEY(task_id) REFERENCES learning_task(id),
 CONSTRAINT fk_learning_assignment_user FOREIGN KEY(user_id) REFERENCES user_profile(id),
 CONSTRAINT chk_learning_allocation CHECK(allocation_status IN ('ACTIVE','REVOKED')),
 CONSTRAINT chk_learning_progress CHECK(progress IN ('NOT_STARTED','PENDING_REVIEW','REJECTED','COMPLETED')),
 CONSTRAINT chk_learning_completion CHECK(progress<>'COMPLETED' OR completed_at IS NOT NULL),
 CONSTRAINT chk_learning_first_submission CHECK((first_submitted_at IS NULL)=(on_time_first_submission IS NULL)),
 CONSTRAINT chk_learning_revocation CHECK(allocation_status<>'REVOKED' OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL AND revocation_reason IS NOT NULL)),
 KEY idx_learning_my(user_id,assigned_at,id),
 KEY idx_learning_progress(task_id,allocation_status,progress,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE learning_task_submission (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 task_id BIGINT UNSIGNED NOT NULL,
 assignment_id BIGINT UNSIGNED NOT NULL,
 attempt INT UNSIGNED NOT NULL,
 text TEXT NULL,
 file_ids JSON NOT NULL,
 confirmed_at DATETIME(6) NULL,
 submitted_at DATETIME(6) NOT NULL,
 review_status VARCHAR(24) NOT NULL,
 reviewed_at DATETIME(6) NULL,
 reviewed_by BIGINT UNSIGNED NULL,
 review_reason VARCHAR(1000) NULL,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 pending_assignment_id BIGINT UNSIGNED GENERATED ALWAYS AS (IF(review_status='PENDING_REVIEW',assignment_id,NULL)) STORED,
 UNIQUE KEY uk_learning_attempt(assignment_id,attempt),
 UNIQUE KEY uk_learning_pending(pending_assignment_id),
 UNIQUE KEY uk_learning_submission_chain(id,assignment_id),
 CONSTRAINT fk_learning_submission_assignment FOREIGN KEY(assignment_id,task_id) REFERENCES learning_task_assignment(id,task_id),
 CONSTRAINT chk_learning_attempt CHECK(attempt>0),
 CONSTRAINT chk_learning_review CHECK(review_status IN ('NOT_REQUIRED','PENDING_REVIEW','APPROVED','REJECTED')),
 CONSTRAINT chk_learning_review_facts CHECK(
   (review_status IN ('APPROVED','REJECTED') AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL)
   OR (review_status IN ('NOT_REQUIRED','PENDING_REVIEW') AND reviewed_at IS NULL AND reviewed_by IS NULL AND review_reason IS NULL)),
 CONSTRAINT chk_learning_rejection_reason CHECK(review_status<>'REJECTED' OR review_reason IS NOT NULL),
 CONSTRAINT chk_learning_material CHECK(text IS NOT NULL OR JSON_LENGTH(file_ids)>0),
 KEY idx_learning_review_queue(review_status,submitted_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
ALTER TABLE learning_task_assignment ADD CONSTRAINT fk_learning_latest_submission
 FOREIGN KEY(latest_submission_id,id) REFERENCES learning_task_submission(id,assignment_id);
CREATE TABLE learning_task_preview (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 task_id BIGINT UNSIGNED NOT NULL,
 task_revision BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 purpose VARCHAR(8) NOT NULL,
 audience JSON NOT NULL,
 user_ids JSON NOT NULL,
 created_at DATETIME(6) NOT NULL,
 expires_at DATETIME(6) NOT NULL,
 CONSTRAINT fk_learning_preview_task FOREIGN KEY(task_id) REFERENCES learning_task(id),
 CONSTRAINT chk_learning_preview_purpose CHECK(purpose IN ('PUBLISH','ADD')),
 KEY idx_learning_preview_owner(task_id,actor_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE learning_task_request (
 actor_scope VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 operation VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 target_id BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 result JSON NULL,
 created_at DATETIME(6) NOT NULL,
 PRIMARY KEY(actor_scope,operation,target_id,request_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE learning_task_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 task_id BIGINT UNSIGNED NOT NULL,
 assignment_id BIGINT UNSIGNED NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 operation VARCHAR(64) NOT NULL,
 reason VARCHAR(1000) NULL,
 before_state VARCHAR(64) NOT NULL,
 after_state VARCHAR(64) NOT NULL,
 exceptional BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(6) NOT NULL,
 CONSTRAINT fk_learning_audit_task FOREIGN KEY(task_id) REFERENCES learning_task(id),
 CONSTRAINT fk_learning_audit_assignment FOREIGN KEY(assignment_id,task_id) REFERENCES learning_task_assignment(id,task_id),
 KEY idx_learning_audit_task(task_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
